def _collect_mumford_candidate_x_values(obj: Any, out: Optional[List[Any]] = None) -> List[Any]:
    """
    Recursively collect candidate x-values from a Mumford payload.

    This is intentionally permissive:
    - explicit x-like fields are preserved
    - leaf dict keys are treated as x-candidates when the dict looks like an
      x_res -> solutions map
    - nested tuples/lists/sets are scanned everywhere, not just at one fixed slot
    """
    if out is None:
        out = []

    if obj is None:
        return out

    def _add(x):
        if x is not None:
            out.append(x)

    if isinstance(obj, dict):
        # Explicit x-like payloads first.
        for key in ("xj", "x", "x_val", "xcoord", "candidate_x", "x_value"):
            if key in obj and obj[key] is not None:
                _add(obj[key])

        # If this looks like a leaf residue map, treat keys as candidates.
        # Common shape: x_res -> solutions, where values are lists/tuples/sets.
        if obj and all(not isinstance(v, dict) for v in obj.values()):
            for k, v in obj.items():
                if isinstance(v, (list, tuple, set)) and not isinstance(k, (list, tuple, set, dict)):
                    _add(k)

        for value in obj.values():
            _collect_mumford_candidate_x_values(value, out)
        return out

    if isinstance(obj, (list, tuple, set)):
        for value in obj:
            _collect_mumford_candidate_x_values(value, out)
        return out

    return out

